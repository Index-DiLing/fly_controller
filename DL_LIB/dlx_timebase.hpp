#pragma once
//===================================================================================================
// dlx_timebase.hpp —— 把"会回绕的硬件周期计数器"展开成**单调微秒时基**(纯逻辑, 主机可测)
//
// 为什么需要这个文件(2026-10-06 上板实测抓到的第二个真元凶):
//
//   `DWT->CYCCNT` 是 **32 位周期计数器**, 168MHz 下每 2^32 / 168e6 = **25.57 秒**回绕一次。
//   而 `CYCCNT / 168`(想直接得到微秒)并**不会**把回绕也解决掉 —— 它只是把回绕点从
//   "2^32 个周期"搬到"2^32/168 微秒", **仍然是 25.57 秒**。于是所有基于 uint32 微秒的判据
//   (采信前置的"两帧最短间隔"、时分从端的相位网格)每 25.6 秒就会看到一次"时间倒退"。
//
//   上板现象(实测日志, 这一条是逐字读出来的):
//     `[Link] 链路=超时(距上次指令 6069ms) 收字节=7136 收帧=892 拒=0 采信拒=246
//            采纳=646 发帧=99`  —— 一秒后: 收帧 +33、采信拒 +33、采纳不动、发帧不动。
//     收帧 = 33/s = 遥控器上行 33.3Hz ⇒ **每一帧都收到了也解出来了**; 而"采信拒"同速增长
//     ⇒ **每一帧都被准入门拒掉**。冻结时刻 = 运行 25.9s ≈ CYCCNT 的回绕点。
//
//   机制: 回绕那一刻 `since = nowUs - m_lastRxUs` 变成"半程以上的巨大值", 判据把它读成
//   "时基倒退"并弃帧; 而 `m_lastRxUs` **只在采信时才更新** ⇒ 判据永远无法自愈, 要等 nowUs
//   重新追上旧值(计数器半程, 几十分钟)。链路从"完全正常"直接变成"一帧都不采信"。
//
// 本文件的职责只有一件: 把"每 25.6 秒回绕一次"的周期数, 用**无符号差分**累加成单调微秒数
//   (于是回绕周期变成 2^32 微秒 ≈ 71.6 分钟)。
//
// ⚠ 它**不能**消除回绕本身, 也不该假装能: 71.6 分钟后仍会回绕一次。所以**调用方的"时间倒退"
//   分支必须重新对齐, 而不是把这一帧(以及之后所有帧)判死** —— 见 FrameAdmission::admit 与
//   SchedSlave::onMasterFrame 里的那两段。一句话: **回绕不可怕, 判据不能自愈才可怕。**
//===================================================================================================
#include <stdint.h>

namespace dlx
{
    /** 展开器状态(调用方持有; 一个时基一个实例) */
    struct UsExpander
    {
        uint32_t lastCycles = 0u; ///< 上一次读到的原始周期数
        uint64_t accUs      = 0u; ///< 累计微秒(单调; 只在返回时截成 uint32)
        uint32_t remCycles  = 0u; ///< 除不尽的余数(丢余数会以"每读一次差 1µs"的方式累积漂移)
    };

    /**
     * @brief 推进一次: 给"当前周期数"与"每微秒几个周期", 返回**单调微秒**时间戳
     *
     * 为什么用无符号差分: `cycles - lastCycles` 在 32 位无符号下**天然跨回绕正确**(模 2^32 减法),
     *   不需要任何 `if (now < last)` 分支 —— 那种分支恰恰是"回绕时刻判错"最常见的来源。
     * 为什么保留余数: 168 周期 = 1µs, 每次截断会把最多 167 个周期白扔掉; 8ms 轮询下一次一轮丢
     *   约 1µs ⇒ 每小时漂 0.45 秒。对"槽长/超时"这种判据不算致命, 但没有理由白扔 ——
     *   而且它会掩盖"时基到底准不准"这件事(排查定时问题时最不该有的误差源)。
     */
    inline uint32_t usExpanderStep(UsExpander &s, uint32_t cycles, uint32_t cyclesPerUs)
    {
        if (cyclesPerUs == 0u) {
            return (uint32_t)s.accUs; // 时钟没配对: 不猜(调用方的迭代兜底会保证不死等)
        }
        const uint32_t delta = (uint32_t)(cycles - s.lastCycles); // 跨回绕正确
        s.lastCycles         = cycles;
        const uint64_t total = (uint64_t)s.remCycles + (uint64_t)delta; // 64 位: delta 可能接近 2^32
        s.accUs += total / cyclesPerUs;
        s.remCycles = (uint32_t)(total % cyclesPerUs);
        return (uint32_t)s.accUs;
    }

    /** 毫秒视图(同一份累加器)。给"只关心几十毫秒量级超时"的驱动用(如 E220 的 AT 等待) */
    inline uint32_t usExpanderMillis(const UsExpander &s) { return (uint32_t)(s.accUs / 1000u); }
} // namespace dlx
